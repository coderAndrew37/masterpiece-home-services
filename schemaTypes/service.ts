// sanity/schemas/service.ts
import {defineField, defineType} from 'sanity'
import {WrenchIcon} from '@sanity/icons/Wrench'

export const service = defineType({
  name: 'service',
  title: 'Service',
  type: 'document',
  icon: WrenchIcon,
  groups: [
    {name: 'listing', title: 'Listing (Cards)', default: true},
    {name: 'detail', title: 'Detail Page'},
    {name: 'gallery', title: 'Gallery'},
    {name: 'seo', title: 'SEO'},
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      validation: (Rule) => Rule.required(),
      group: ['listing', 'detail'],
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      options: {source: 'title', maxLength: 96},
      validation: (Rule) => Rule.required(),
      group: ['listing', 'detail'],
    }),
    defineField({
      name: 'order',
      title: 'Display Order',
      type: 'number',
      description: 'Lower numbers show first on the services grid.',
      initialValue: 0,
      group: 'listing',
    }),
    defineField({
      name: 'featuredOnHome',
      title: 'Show on Homepage',
      type: 'boolean',
      description: 'Only the first 4 (by Display Order) featured services show on the homepage cards.',
      initialValue: false,
      group: 'listing',
    }),
    defineField({
      name: 'homeSubtitle',
      title: 'Homepage Card Subtitle',
      type: 'string',
      description: 'Short line for the homepage card. Falls back to Short Description if empty.',
      group: 'listing',
    }),
    defineField({
      name: 'badge',
      title: 'Badge',
      type: 'string',
      description: 'e.g. "Most Popular", "New Service", "Seasonal"',
      group: ['listing', 'detail'],
    }),
    defineField({
      name: 'icon',
      title: 'Icon',
      type: 'string',
      options: {
        list: [
          {title: 'Home', value: 'FiHome'},
          {title: 'Droplet', value: 'FiDroplet'},
          {title: 'Sun', value: 'FiSun'},
          {title: 'Zap', value: 'FiZap'},
          {title: 'Shield', value: 'FiShield'},
          {title: 'Calendar', value: 'FiCalendar'},
        ],
        layout: 'dropdown',
      },
      initialValue: 'FiHome',
      validation: (Rule) => Rule.required(),
      group: 'listing',
    }),
    defineField({
      name: 'cardImage',
      title: 'Card Image',
      type: 'image',
      options: {hotspot: true},
      fields: [{name: 'alt', title: 'Alternative Text', type: 'string'}],
      validation: (Rule) => Rule.required(),
      group: 'listing',
    }),
    defineField({
      name: 'shortDescription',
      title: 'Short Description',
      type: 'text',
      rows: 3,
      validation: (Rule) => Rule.required().max(200),
      group: 'listing',
    }),
    defineField({
      name: 'features',
      title: 'Card Features',
      type: 'array',
      of: [{type: 'string'}],
      validation: (Rule) => Rule.max(6),
      group: 'listing',
    }),
    defineField({
      name: 'subtitle',
      title: 'Subtitle',
      type: 'string',
      description: 'Shown under the title in the detail page hero.',
      validation: (Rule) => Rule.required(),
      group: 'detail',
    }),
    defineField({
      name: 'heroImage',
      title: 'Hero Image',
      type: 'image',
      options: {hotspot: true},
      fields: [{name: 'alt', title: 'Alternative Text', type: 'string'}],
      description: 'Falls back to Card Image if left empty.',
      group: 'detail',
    }),
    defineField({
      name: 'startingPrice',
      title: 'Starting Price',
      type: 'string',
      description: 'e.g. "$199" or "from $299"',
      validation: (Rule) => Rule.required(),
      group: ['listing', 'detail'],
    }),
    defineField({
      name: 'description',
      title: 'Service Overview',
      type: 'blockContent',
      group: 'detail',
    }),
    defineField({
      name: 'whatsIncluded',
      title: "What's Included",
      type: 'array',
      of: [{type: 'string'}],
      group: 'detail',
    }),
    defineField({
      name: 'benefits',
      title: 'Key Benefits',
      type: 'array',
      of: [{type: 'string'}],
      group: 'detail',
    }),
    defineField({
      name: 'processSteps',
      title: 'Process Steps',
      type: 'array',
      of: [{type: 'processStep'}],
      group: 'detail',
    }),
    defineField({
      name: 'faqs',
      title: 'FAQs',
      type: 'array',
      of: [{type: 'faq'}],
      group: 'detail',
    }),
    defineField({
      name: 'gallery',
      title: 'Gallery',
      type: 'array',
      of: [{type: 'galleryImage'}],
      options: {layout: 'grid'},
      group: 'gallery',
    }),
    defineField({
      name: 'seoTitle',
      title: 'SEO Title',
      type: 'string',
      group: 'seo',
    }),
    defineField({
      name: 'seoDescription',
      title: 'SEO Description',
      type: 'text',
      rows: 2,
      validation: (Rule) => Rule.max(160),
      group: 'seo',
    }),
  ],
  preview: {
    select: {title: 'title', subtitle: 'shortDescription', media: 'cardImage', badge: 'badge'},
    prepare({title, subtitle, media, badge}) {
      return {title: badge ? `${title} · ${badge}` : title, subtitle, media}
    },
  },
  orderings: [
    {title: 'Display Order', name: 'orderAsc', by: [{field: 'order', direction: 'asc'}]},
    {title: 'Title A-Z', name: 'titleAsc', by: [{field: 'title', direction: 'asc'}]},
  ],
})